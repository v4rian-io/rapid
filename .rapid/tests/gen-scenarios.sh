#!/usr/bin/env bash
# tests/gen-scenarios.sh [--check] - write tests/SCENARIOS.md from the header
# comment of every scenario; --check fails when the file is stale.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
gen() {
  printf '# Scenario matrix\n\nGenerated by tests/gen-scenarios.sh from each scenario'"'"'s header; do not edit.\n'
  printf 'Run: `sh .rapid/tests/run.sh [--fast] [-j N] [FILTER]` (N at once; default RAPID_TEST_JOBS or every scenario at once). Fast subset: marked `fast`.\n\n'
  printf '| Scenario | Fast | Verifies |\n|---|---|---|\n'
  for s in "$here"/scenarios/*.sh; do
    name=$(basename "$s" .sh)
    fast=""; [[ "$(sed -n 2p "$s")" == '# fast'* ]] && fast=yes
    text=$(awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); if ($0 ~ /^fast/) next; printf "%s ", $0; next } { exit }' "$s" | sed -E 's/[[:space:]]+$//; s/\|/\\|/g')
    printf '| %s | %s | %s |\n' "$name" "$fast" "$text"
  done
}
if [ "${1:-}" = --check ]; then
  diff -u "$here/SCENARIOS.md" <(gen) >/dev/null || { echo "X tests/SCENARIOS.md is stale; run sh .rapid/tests/gen-scenarios.sh" >&2; exit 1; }
else
  gen > "$here/SCENARIOS.md"
fi
